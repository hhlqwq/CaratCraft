SET NAMES utf8mb4;
START TRANSACTION READ ONLY;
SELECT MENU_ID,PARENT_ID,NAME,PERMS FROM SYS_MENU WHERE MENU_ID IN
('1802','180201','1803','180301','180302','180104','180105','180106','180107','180108','140602','110106')
ORDER BY MENU_ID;
SELECT r.ROLE_ID,r.ROLE_NAME,r.DELEGABLE,m.MENU_ID,m.PERMS,ro.ORG_NO
FROM SYS_ROLE r LEFT JOIN SYS_ROLE_MENU rm ON rm.ROLE_ID=r.ROLE_ID
LEFT JOIN SYS_MENU m ON m.MENU_ID=rm.MENU_ID LEFT JOIN SYS_ROLE_ORG ro ON ro.ROLE_ID=r.ROLE_ID
WHERE r.ROLE_ID LIKE 'cc-job-%' ORDER BY r.ROLE_ID,m.MENU_ID,ro.ORG_NO;
SELECT USER_ID,ROLE_ID FROM SYS_USER_ROLE WHERE ROLE_ID LIKE 'cc-job-%' ORDER BY USER_ID,ROLE_ID;
SELECT 'goods' AS resource_type,COUNT(*) AS unmapped FROM mall_goods WHERE scope_org_no IS NULL
UNION ALL SELECT 'order',COUNT(*) FROM mall_order WHERE scope_org_no IS NULL
UNION ALL SELECT 'feedback',COUNT(*) FROM mall_feedback WHERE scope_org_no IS NULL
UNION ALL SELECT 'community',COUNT(*) FROM CC_COMMUNITY_POST WHERE scope_org_no IS NULL
UNION ALL SELECT 'audit',COUNT(*) FROM SYS_LOG WHERE SCOPE_ORG_NO IS NULL;
ROLLBACK;
