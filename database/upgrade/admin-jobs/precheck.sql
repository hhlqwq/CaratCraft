SET NAMES utf8mb4;
-- 只读盘点. 查询结果不得包含密码、令牌和联系方式.
START TRANSACTION READ ONLY;
SELECT u.USER_ID,u.USER_NAME,u.ORG_NO,u.STATUS,COUNT(DISTINCT ur.ROLE_ID) AS role_count,
       GROUP_CONCAT(DISTINCT CONCAT(r.ROLE_ID,':',r.ROLE_NAME) ORDER BY r.ROLE_ID) AS roles
FROM SYS_USER u LEFT JOIN SYS_USER_ROLE ur ON ur.USER_ID=u.USER_ID
LEFT JOIN SYS_ROLE r ON r.ROLE_ID=ur.ROLE_ID
GROUP BY u.USER_ID,u.USER_NAME,u.ORG_NO,u.STATUS ORDER BY u.USER_ID;
SELECT r.ROLE_ID,r.ROLE_NAME,m.MENU_ID,m.PERMS,
       (SELECT COUNT(DISTINCT ur.USER_ID) FROM SYS_USER_ROLE ur WHERE ur.ROLE_ID=r.ROLE_ID) AS staff_count
FROM SYS_ROLE r JOIN SYS_ROLE_MENU rm ON r.ROLE_ID=rm.ROLE_ID
JOIN SYS_MENU m ON rm.MENU_ID=m.MENU_ID
WHERE m.PERMS REGEXP 'mall:order:update|mall:refund|[*]' OR m.PERMS IN ('mall','mall:order')
ORDER BY r.ROLE_ID,m.MENU_ID;
SELECT ur.USER_ID,r.ROLE_ID,m.PERMS,ro.ORG_NO FROM SYS_USER_ROLE ur
JOIN SYS_ROLE r ON r.ROLE_ID=ur.ROLE_ID JOIN SYS_ROLE_MENU rm ON rm.ROLE_ID=r.ROLE_ID
JOIN SYS_MENU m ON m.MENU_ID=rm.MENU_ID LEFT JOIN SYS_ROLE_ORG ro ON ro.ROLE_ID=r.ROLE_ID
WHERE m.PERMS IS NOT NULL AND m.PERMS<>'' ORDER BY ur.USER_ID,r.ROLE_ID,m.MENU_ID,ro.ORG_NO;
SELECT MENU_ID,PARENT_ID,NAME,PERMS,TYPE FROM SYS_MENU
WHERE MENU_ID IN ('1802','180201','1803','180301','180302','180104','180105','180106','180107','180108','140602','110106');
SELECT ROLE_ID,ROLE_NAME FROM SYS_ROLE WHERE ROLE_ID LIKE 'cc-job-%';
ROLLBACK;
