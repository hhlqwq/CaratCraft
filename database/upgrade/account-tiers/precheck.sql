SET NAMES utf8mb4;
START TRANSACTION READ ONLY;

SELECT u.USER_ID, u.USER_NAME, u.STATUS, u.ORG_NO, o.ORG_NAME,
       CASE WHEN u.USER_ID='1' THEN 'PLATFORM_ADMIN' ELSE 'CONFIRM_MAPPING' END AS SUGGESTED_TIER
FROM SYS_USER u LEFT JOIN SYS_ORG o ON o.ORG_NO=u.ORG_NO ORDER BY u.USER_ID;

SELECT ur.USER_ID, r.ROLE_ID, r.ROLE_NAME, ro.ORG_NO, r.DELEGABLE
FROM SYS_USER_ROLE ur LEFT JOIN SYS_ROLE r ON r.ROLE_ID=ur.ROLE_ID
LEFT JOIN SYS_ROLE_ORG ro ON ro.ROLE_ID=r.ROLE_ID
ORDER BY ur.USER_ID, r.ROLE_ID, ro.ORG_NO;

SELECT o.ORG_NO, o.ORG_NAME, o.STATUS FROM SYS_ORG o ORDER BY o.ORG_NO;
SELECT 'goods' AS RESOURCE, COUNT(*) AS UNASSIGNED FROM mall_goods WHERE NULLIF(TRIM(scope_org_no),'') IS NULL
UNION ALL SELECT 'order', COUNT(*) FROM mall_order WHERE NULLIF(TRIM(scope_org_no),'') IS NULL
UNION ALL SELECT 'feedback', COUNT(*) FROM mall_feedback WHERE NULLIF(TRIM(scope_org_no),'') IS NULL
UNION ALL SELECT 'community', COUNT(*) FROM CC_COMMUNITY_POST WHERE NULLIF(TRIM(scope_org_no),'') IS NULL;
ROLLBACK;
