const jewelVertex = [
    'attribute vec3 aPosition;',
    'attribute vec3 aNormal;',
    'uniform mat4 uProjection;',
    'uniform mat3 uRotation;',
    'uniform vec3 uCenter;',
    'uniform float uRadius;',
    'uniform float uDistance;',
    'varying vec3 vPosition;',
    'varying vec3 vNormal;',
    'varying vec3 vLocal;',
    'void main() {',
    '    vLocal = aPosition;',
    '    vPosition = uRotation * (uCenter + aPosition * uRadius) - vec3(0.0, 0.0, uDistance);',
    '    vNormal = uRotation * aNormal;',
    '    gl_Position = uProjection * vec4(vPosition, 1.0);',
    '}',
].join('\n');

const jewelFragment = [
    'varying vec3 vPosition;',
    'varying vec3 vNormal;',
    'varying vec3 vLocal;',
    'uniform mat3 uRotation;',
    'uniform float uMaterial;',
    'uniform float uSeed;',
    '',
    // 以视图坐标的软箱拟合离线摄影棚反射. 所有颜色在线性空间累积.
    'float panel(vec3 ray, vec3 forward, vec3 right, vec3 up, vec2 size, float blur) {',
    '    float facing = dot(ray, forward);',
    '    vec2 point = abs(vec2(dot(ray, right), dot(ray, up))) / max(0.16, facing);',
    '    vec2 spread = 1.0 - smoothstep(max(vec2(0.0), size - blur), size + blur, point);',
    '    return spread.x * spread.y * smoothstep(0.1, 0.5, facing);',
    '}',
    '',
    'vec3 studio(vec3 ray, float blur) {',
    '    float key = panel(ray, vec3(-0.516, 0.600, 0.611), vec3(0.764, 0.0, 0.645),',
    '        vec3(0.387, 0.800, -0.458), vec2(0.27, 0.42), blur);',
    '    float strip = panel(ray, vec3(0.733, 0.365, 0.572), vec3(0.615, 0.0, -0.788),',
    '        vec3(-0.288, 0.931, -0.225), vec2(0.10, 0.56), blur * 0.62);',
    '    float foot = panel(ray, vec3(-0.205, -0.883, 0.423), vec3(0.900, 0.0, 0.436),',
    '        vec3(0.385, -0.469, -0.795), vec2(0.74, 0.19), blur * 1.8);',
    '    float darkCard = smoothstep(0.08, 0.88, dot(ray, vec3(0.78, -0.50, -0.36)));',
    '    vec3 room = vec3(0.109, 0.115, 0.124) * (1.0 - 0.71 * darkCard);',
    '    room += vec3(0.185, 0.137, 0.090) * smoothstep(-0.9, 0.65, ray.y);',
    '    room += key * vec3(2.55, 2.43, 2.30);',
    '    room += strip * vec3(0.97, 1.08, 1.28);',
    '    room += foot * vec3(0.62, 0.42, 0.29);',
    '    return room;',
    '}',
    '',
    'vec3 grade(vec3 light) {',
    '    vec3 x = max(vec3(0.0), light);',
    '    vec3 filmic = (x * (2.51 * x + 0.03)) / (x * (2.43 * x + 0.59) + 0.14);',
    '    return pow(clamp(filmic, 0.0, 1.0), vec3(0.454545));',
    '}',
    '',
    'void main() {',
    '    vec3 n = normalize(vNormal);',
    '    vec3 eye = normalize(-vPosition);',
    '    vec3 ray = reflect(-eye, n);',
    '    float view = max(0.0, dot(n, eye));',
    '    if (uMaterial > 1.5) {',
    '        float light = 0.50 + 0.48 * max(0.0, dot(n, vec3(-0.45, 0.62, 0.64)));',
    '        gl_FragColor = vec4(grade(light * vec3(0.34, 0.25, 0.17)), 1.0);',
    '        return;',
    '    }',
    '    if (uMaterial > 0.5) {',
    '        vec3 reflection = studio(ray, 0.049);',
    '        float edge = pow(1.0 - view, 5.0);',
    '        vec3 champagne = mix(vec3(0.83, 0.79, 0.72), vec3(1.0), edge * 0.62);',
    '        vec3 glint = pow(max(0.0, dot(ray, vec3(-0.516, 0.600, 0.611))), 138.0)',
    '            * vec3(0.59, 0.54, 0.47);',
    '        gl_FragColor = vec4(grade(reflection * champagne * 0.92 + glint), 1.0);',
    '        return;',
    '    }',
    '',
    // 局部纹理调制法线和膜色, 用宽散射层与窄反射层分离母贝光泽.
    '    vec3 p = normalize(vLocal);',
    '    float fine = sin(p.y * 101.0 + p.x * 7.4 + sin(p.z * 13.0))',
    '        * cos(p.z * 87.3 + p.x * 12.6);',
    '    float contour = sin(p.x * 18.0 + p.z * 9.0 + sin(p.y * 6.9) + uSeed * 9.0);',
    '    vec3 relief = vec3(0.014 * contour, 0.009 * fine, 0.009 * contour * fine);',
    '    n = normalize(n + uRotation * relief);',
    '    ray = reflect(-eye, n);',
    '    view = max(0.0, dot(n, eye));',
    '    float rim = 1.0 - view;',
    '    float bias = sin(uSeed * 17.431);',
    '    float wave = (1.0 - rim * 0.72) * (6.9 + 0.31 * contour) + uSeed * 0.34 + 0.36 * p.x + 0.14 * p.z;',
    '    vec3 film = vec3(0.5) + vec3(0.5) * cos(wave + vec3(0.43, 2.51, 4.83));',
    '    vec3 base = vec3(0.785, 0.705, 0.608) + bias * vec3(0.032, 0.025, 0.023);',
    '    base = mix(base, base * vec3(0.94, 1.08, 1.11), 0.44 * smoothstep(-0.39, 0.66, p.x + 0.38 * p.z));',
    '    float light = dot(n, vec3(-0.516, 0.600, 0.611));',
    '    float wrap = smoothstep(-0.60, 0.91, light);',
    '    float bounce = max(0.0, dot(n, vec3(0.57, -0.58, 0.58))) * 0.12;',
    '    vec3 body = base * (0.255 + 0.61 * wrap + bounce);',
    '    body *= (0.983 + contour * 0.019 + fine * 0.008);',
    '    body += (film - 0.50) * (0.040 + 0.087 * pow(rim, 1.05));',
    '    vec3 broad = studio(ray, 0.28);',
    '    vec3 sharp = studio(ray, 0.073);',
    '    float fresnel = 0.105 + 0.39 * pow(rim, 2.4);',
    '    vec3 nacre = mix(broad, sharp, 0.60) * fresnel;',
    '    nacre *= mix(vec3(1.0), vec3(0.87) + film * 0.26, pow(rim, 1.3));',
    '    float pearlEdge = smoothstep(0.44, 1.0, rim);',
    '    body *= mix(1.0, 0.67, pearlEdge);',
    '    gl_FragColor = vec4(grade(body + nacre), 1.0);',
    '}',
].join('\n');

const backdropVertex = [
    'attribute vec2 aPosition;',
    'varying vec2 vScreen;',
    'void main() {',
    '    vScreen = aPosition;',
    '    gl_Position = vec4(aPosition, 0.0, 1.0);',
    '}',
].join('\n');

const backdropFragment = [
    'varying vec2 vScreen;',
    'void main() {',
    '    vec2 light = vScreen - vec2(-0.34, 0.52);',
    '    float tone = exp(-0.58 * dot(light, light));',
    '    float grain = fract(sin(dot(gl_FragCoord.xy, vec2(12.9898, 78.233))) * 43758.5453) - 0.5;',
    '    vec3 backdrop = mix(vec3(0.708, 0.659, 0.590), vec3(0.884, 0.849, 0.791), tone);',
    '    gl_FragColor = vec4(backdrop + grain * 0.011, 1.0);',
    '}',
].join('\n');

const shadowVertex = [
    'attribute vec2 aPosition;',
    'attribute vec2 aProfile;',
    'attribute float aOpacity;',
    'varying vec2 vProfile;',
    'varying float vOpacity;',
    'void main() {',
    '    vProfile = aProfile;',
    '    vOpacity = aOpacity;',
    '    gl_Position = vec4(aPosition, 0.0, 1.0);',
    '}',
].join('\n');

const shadowFragment = [
    'varying vec2 vProfile;',
    'varying float vOpacity;',
    'void main() {',
    '    float spread = dot(vProfile, vProfile);',
    '    float alpha = (0.72 * exp(-5.2 * spread) + 0.22 * exp(-21.0 * spread)) * vOpacity;',
    '    alpha *= 1.0 - smoothstep(0.62, 1.0, spread);',
    '    gl_FragColor = vec4(0.239, 0.180, 0.127, alpha);',
    '}',
].join('\n');

const haloVertex = [
    'attribute vec2 aPosition;',
    'uniform mat4 uProjection;',
    'uniform vec3 uCenter;',
    'uniform float uRadius;',
    'varying vec2 vRing;',
    'void main() {',
    '    vRing = aPosition;',
    '    gl_Position = uProjection * vec4(uCenter + vec3(aPosition * uRadius, 0.0), 1.0);',
    '}',
].join('\n');

const haloFragment = [
    'varying vec2 vRing;',
    'void main() {',
    '    float r = length(vRing);',
    '    float edge = smoothstep(0.85, 0.89, r) * (1.0 - smoothstep(0.93, 0.99, r));',
    '    gl_FragColor = vec4(0.153, 0.309, 0.242, edge * 0.89);',
    '}',
].join('\n');

